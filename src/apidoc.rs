//! The API reference (docs/api.md), generated from the one operation table in `rpc::tools`.
//! `treeyard api-doc > docs/api.md` writes it; `tests/docs.rs` fails when the file is stale.

use serde_json::Value;
use std::fmt::Write as _;

/// Groups of operations, in the order of the reference. Every tool must be in one group.
pub const GROUPS: &[(&str, &[&str])] = &[
    ("Read without a checkout", &["status", "read", "list", "tree", "blobs", "grep", "diff"]),
    ("History and code intelligence", &["log", "blame", "symbols", "outline", "bisect"]),
    ("Changes", &["open_change", "declare", "apply", "resolve", "rebase", "land", "abandon", "revert"]),
    ("Best of N", &["group", "land_one_of"]),
    ("Checkpoints and attachments", &["checkpoint", "checkpoints", "restore_change", "attach", "attachments"]),
    ("Inspect changes", &["change", "changes", "export_change"]),
    ("Coordination", &["events", "reviews", "review_close", "queue", "queue_run", "test_main", "config"]),
    ("Access and audit", &["whoami", "token_create", "token_list", "token_revoke", "audit"]),
];

fn type_of(schema: &Value) -> String {
    if let Some(ts) = schema["type"].as_array() {
        let names: Vec<&str> = ts.iter().filter_map(Value::as_str).collect();
        return names.join(" or ");
    }
    let t = schema["type"].as_str().unwrap_or("any");
    match t {
        "array" => format!("array of {}", type_of(&schema["items"])),
        "string" => match schema["enum"].as_array() {
            Some(e) => {
                let names: Vec<String> = e.iter().filter_map(Value::as_str).map(|s| format!("`{s}`")).collect();
                format!("one of {}", names.join(", "))
            }
            None => "string".into(),
        },
        "object" => match schema["properties"].as_object() {
            Some(p) if !p.is_empty() => {
                let keys: Vec<String> = p.keys().map(|k| format!("`{k}`")).collect();
                format!("object ({})", keys.join(", "))
            }
            _ => "object".into(),
        },
        other => other.into(),
    }
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

/// The Markdown reference for every operation of `tools`.
pub fn markdown(tools: &[Value]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# API reference\n");
    let _ = writeln!(
        out,
        "Generated by `treeyard api-doc` from the operation table in `src/rpc.rs`. Do not edit by hand: \
         `tests/docs.rs` fails when this file and the table differ.\n"
    );
    let _ = writeln!(
        out,
        "Every operation has three transports. All three take the same JSON parameters and give the same JSON reply.\n"
    );
    let _ = writeln!(out, "| Transport | Call |\n|---|---|");
    let _ = writeln!(
        out,
        "| HTTP | `POST /api/<op>` with a JSON object body; reply `200` with JSON, or an error status with `{{\"error\": \"...\"}}` |"
    );
    let _ = writeln!(
        out,
        "| MCP (stdio) | `tools/call` with `name` = `<op>` and `arguments` = the parameters (`treeyard mcp`) |"
    );
    let _ = writeln!(
        out,
        "| CLI | `treeyard call <op> '<json>'` (server from `TREEYARD_URL`, token from `TREEYARD_TOKEN`) |\n"
    );
    let _ = writeln!(
        out,
        "Error statuses: `400` invalid JSON, `401` no valid token, `403` the token has no right, `404` an \
         operation name that is not lowercase letters and `_`, `422` the operation failed (also an unknown \
         operation), `503` the server is busy (retry). The protocol is described in [spec/rpc.md](spec/rpc.md).\n"
    );
    let _ = writeln!(
        out,
        "Other routes: `GET /health` answers `ok`; `GET /api/events` is the server-sent event stream of \
         [`events`](#events); `POST /api/tools` returns this table as JSON (the MCP `tools/list` reply, also \
         `treeyard api-doc --json`); `/git` serves git smart HTTP ([git-http.md](git-http.md)).\n"
    );
    let _ = writeln!(
        out,
        "A revision (`at`, `from`, `to`, `base`, `good`, `bad`, `changeset`) is `main`, a change id `ch_...`, a changeset id or a unique prefix of one, or a 40-hex git commit id.\n"
    );
    let _ = writeln!(out, "## Operations\n");
    for (group, ops) in GROUPS {
        let names: Vec<String> = ops.iter().map(|o| format!("[`{o}`](#{o})")).collect();
        let _ = writeln!(out, "- {group}: {}", names.join(", "));
    }
    for (group, ops) in GROUPS {
        let _ = writeln!(out, "\n## {group}");
        for op in *ops {
            let Some(t) = tools.iter().find(|t| t["name"] == *op) else { continue };
            let _ = writeln!(out, "\n### {op}\n");
            let _ = writeln!(out, "{}\n", t["description"].as_str().unwrap_or_default());
            let schema = &t["inputSchema"];
            let required: Vec<&str> =
                schema["required"].as_array().map(|r| r.iter().filter_map(Value::as_str).collect()).unwrap_or_default();
            match schema["properties"].as_object() {
                Some(props) if !props.is_empty() => {
                    let _ = writeln!(out, "| Parameter | Type | Required | Description |\n|---|---|---|---|");
                    for (name, p) in props {
                        let req = if required.contains(&name.as_str()) { "yes" } else { "no" };
                        let desc = cell(p["description"].as_str().unwrap_or(""));
                        let _ = writeln!(out, "| `{name}` | {} | {req} | {desc} |", cell(&type_of(p)));
                    }
                }
                _ => {
                    let _ = writeln!(out, "No parameters.");
                }
            }
            let _ = writeln!(out, "\n```sh\ntreeyard call {op} '{}'\n```", example(&required));
        }
    }
    out
}

fn example(required: &[&str]) -> String {
    let fields: Vec<String> = required
        .iter()
        .map(|r| match *r {
            "change" => "\"change\": \"ch_...\"".to_string(),
            "edits" => {
                "\"edits\": [{\"path\": \"README.md\", \"replace\": {\"old\": \"teh\", \"new\": \"the\"}}]".to_string()
            }
            "ids" => "\"ids\": [\"<blob id>\"]".to_string(),
            "id" => "\"id\": \"...\"".to_string(),
            "take" => "\"take\": \"ours\"".to_string(),
            "to" => "\"to\": 2".to_string(),
            "group" => "\"group\": \"fix-1\"".to_string(),
            "kind" => "\"kind\": \"summary\"".to_string(),
            "text" => "\"text\": \"why: the parser dropped a trailing comma\"".to_string(),
            "path" => "\"path\": \"README.md\"".to_string(),
            "pattern" => "\"pattern\": \"fn main\"".to_string(),
            "intent" => "\"intent\": \"fix a typo\"".to_string(),
            "name" => "\"name\": \"agent-1\"".to_string(),
            "good" | "changeset" => format!("\"{r}\": \"<changeset id>\""),
            other => format!("\"{other}\": \"...\""),
        })
        .collect();
    format!("{{{}}}", fields.join(", "))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_tool_is_in_one_group() {
        let tools = crate::rpc::tools();
        for t in &tools {
            let name = t["name"].as_str().unwrap();
            let n = GROUPS.iter().filter(|(_, ops)| ops.contains(&name)).count();
            assert_eq!(n, 1, "{name} must be in exactly one group");
        }
        let total: usize = GROUPS.iter().map(|(_, ops)| ops.len()).sum();
        assert_eq!(total, tools.len(), "a group names an operation that is not in the table");
    }
}
